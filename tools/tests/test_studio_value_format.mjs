import fs from 'node:fs';
import assert from 'node:assert/strict';
const source = fs.readFileSync(new URL('../../pb_formula_studio/static/src/js/value_format.js',import.meta.url),'utf8');
const {formatComponentValue:fmt,componentInputType:input} = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const c = kind=>({value_kind:kind,number_format:'currency'});
assert.equal(fmt(c('quantity'),21,'₫'),'21');
assert.equal(fmt(c('quantity'),7.5,'₫'),'7.5');
assert.equal(fmt(c('rate'),.105,'₫'),'10.5%');
assert.equal(fmt(c('identifier'),'00017','₫'),'00017');
assert.equal(fmt(c('text'),'0017','₫'),'0017');
assert.equal(fmt(c('money'),34802300,'₫'),'₫34,802,300');
assert.equal(fmt(c('money'),0,'₫'),'₫0');
assert.equal(fmt(c('money'),-1200,'₫'),'−₫1,200');
assert.equal(fmt(c('boolean'),false,'₫'),'No');
assert.equal(fmt(c('boolean'),true,'₫'),'Yes');
assert.equal(fmt(c('date'),'2026-10-16','₫'),'2026-10-16');
assert.equal(fmt(c('decimal'),undefined,'₫'),'—');
assert.equal(input(c('identifier')),'text');
assert.equal(input(c('date')),'date');
console.log('14 typed-value regression checks passed');
