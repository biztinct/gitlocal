WORD_PATTERN = re.compile(r'\b(' + '|'.join(re.escape(k) for k in sorted(WORD_MAP, key=len, reverse=True)) + r')\b', re.IGNORECASE)


def preserve_case(repl, template):
    if template.isupper():
        return repl.upper()
    if template[:1].isupper():
        return repl[:1].upper() + repl[1:]
    return repl


def apply_replacements(text):
    for pattern, repl in PHRASE_REPLACEMENTS:
        text = re.sub(pattern, repl, text)

    def word_replacer(match):
        key = match.group(0)
        repl = WORD_MAP.get(key.lower(), None)
        if repl is None:
            return key
        return preserve_case(repl, key)

    text = WORD_PATTERN.sub(word_replacer, text)
    text = re.sub(r'\s{2,}', ' ', text)
    text = re.sub(r'\s+([,.;:!?])', r'\1', text)
    return text


def translate_outside_tags(text):
    parts = re.split(r'(<[^>]+>)', text)
    for i, part in enumerate(parts):
        if part.startswith('<') and part.endswith('>'):
            continue
        parts[i] = apply_replacements(part)
    return ''.join(parts)


def parse_po(lines):
    entries = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith('msgid '):
            msgid_lines = [line]
            msgid_parts = [line.split(' ', 1)[1].strip()]
            i += 1
            while i < len(lines) and lines[i].startswith('"'):
                msgid_lines.append(lines[i])
                msgid_parts.append(lines[i].strip())
                i += 1
            msgstr_lines = []
            msgstr_parts = []
            if i < len(lines) and lines[i].startswith('msgstr'):
                msgstr_lines.append(lines[i])
                msgstr_parts.append(lines[i].split(' ', 1)[1].strip())
                i += 1
                while i < len(lines) and lines[i].startswith('"'):
                    msgstr_lines.append(lines[i])
                    msgstr_parts.append(lines[i].strip())
                    i += 1
            entries.append((msgid_lines, msgid_parts, msgstr_lines, msgstr_parts))
        else:
            entries.append((None, None, [line], None))
            i += 1
    return entries


def strip_po_quotes(value):
    if len(value) >= 2 and value[0] == '"' and value[-1] == '"':
        return value[1:-1]
    return value


def build_msgstr_lines(segments):
    if not segments:
        return []
    lines = []
    lines.append('msgstr "{}"\n'.format(segments[0]))
    for seg in segments[1:]:
        lines.append('"{}"\n'.format(seg))
    return lines


def main(path):
    path = pathlib.Path(path)
    lines = path.read_text(encoding='utf-8').splitlines(keepends=True)
    entries = parse_po(lines)
    output = []
    for msgid_lines, msgid_parts, msgstr_lines, msgstr_parts in entries:
        if msgid_lines is None:
            output.extend(msgstr_lines)
            continue

        msgid_text = ''.join(strip_po_quotes(p) for p in msgid_parts)
        msgstr_text = ''.join(strip_po_quotes(p) for p in msgstr_parts)
        is_header = msgid_text == '' and ('Project-Id-Version' in msgstr_text or 'Language:' in msgstr_text)

        if is_header:
            output.extend(msgid_lines)
            output.extend(msgstr_lines)
            continue

        msgstr_segments = [strip_po_quotes(p) for p in msgstr_parts]
        msgid_segments = [strip_po_quotes(p) for p in msgid_parts]
        msgstr_is_empty = all(seg == '' for seg in msgstr_segments)

        if msgstr_is_empty:
            translated_segments = [translate_outside_tags(seg) for seg in msgid_segments]
        else:
            translated_segments = [translate_outside_tags(seg) for seg in msgstr_segments]

        output.extend(msgid_lines)
        output.extend(build_msgstr_lines(translated_segments))

    path.write_text(''.join(output), encoding='utf-8')


