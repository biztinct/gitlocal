/** An icon as markup, for `t-out`. Cached: the same markup object is reused,
 *  so a redraw does not replace the DOM (OWL markup-flicker trap). */
const CACHE = new Map();
export function dsIc(name, size = 16, stroke = 2) {
    const key = `${name}|${size}|${stroke}`;
    if (!CACHE.has(key)) {
        const body = P[name] || P.info;
        CACHE.set(key, markup(
            `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`));
    }
    return CACHE.get(key);
}
